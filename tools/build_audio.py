"""Generate MP3 narration for DevSpeak with neural voices (edge-tts).

Run once on a computer with internet access; the resulting files are plain MP3s
inside the site folder, so the finished site works offline and without a VPN.

    pip install edge-tts
    python tools/build_audio.py            # reads tools/speech.json

tools/speech.json comes from tools/collect.html ("Скачать speech.json").
Existing files are kept; only missing phrases are generated.
"""
import asyncio
import json
import pathlib
import sys

import edge_tts

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "audio"
MANIFEST = ROOT / "assets" / "js" / "data" / "audio.js"

# role -> neural voice
VOICES = {
    "n": "en-US-JennyNeural",        # narrator: lessons, vocabulary, listening
    "video": "en-US-AndrewNeural",   # video lessons
    "kate": "en-US-AvaNeural",       # podcast host
    "max": "en-US-BrianNeural",      # student
    "alex": "en-GB-RyanNeural",      # team lead (British English)
    "tom": "en-US-GuyNeural",        # QA engineer
    "oleg": "en-US-ChristopherNeural",  # listening text "A Day of a Web Master"
}


async def synth(item, sem):
    path = OUT / f"{item['key']}.mp3"
    if path.exists() and path.stat().st_size > 0:
        return True
    voice = VOICES.get(item["role"], VOICES["n"])
    async with sem:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(item["text"], voice).save(str(path))
                if path.stat().st_size > 0:
                    return True
            except Exception as exc:  # network hiccups: retry with backoff
                print(f"  retry {attempt + 1} for {item['key']}: {exc}", file=sys.stderr)
                await asyncio.sleep(1.5 * (attempt + 1))
    if path.exists():
        path.unlink()
    return False


async def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools" / "speech.json"
    items = json.loads(src.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    sem = asyncio.Semaphore(4)
    results = await asyncio.gather(*(synth(i, sem) for i in items))

    keys = sorted(i["key"] for i, ok in zip(items, results) if ok)
    wanted = set(keys)
    removed = 0
    for f in OUT.glob("*.mp3"):
        if f.stem not in wanted:
            f.unlink()
            removed += 1

    MANIFEST.write_text(
        "/* Generated by tools/build_audio.py: pre-recorded narration files in assets/audio/ */\n"
        "window.DS = window.DS || {};\n"
        "DS.audioMap = {" + ",".join(f'"{k}":1' for k in keys) + "};\n",
        encoding="utf-8",
    )
    failed = len(items) - len(keys)
    print(f"Ready: {len(keys)} files, failed: {failed}, removed stale: {removed}")
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    asyncio.run(main())
